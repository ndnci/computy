import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const catalogs = JSON.parse(readFileSync('src/locales/catalogs.json', 'utf8'));
const overrides = JSON.parse(readFileSync('src/locales/overrides.json', 'utf8'));
for (const [language, values] of Object.entries(overrides))
  Object.assign(catalogs[language], values);
writeFileSync('src/locales/catalogs.json', JSON.stringify(catalogs, null, 2) + '\n');
mkdirSync('src/locales/messages', { recursive: true });
for (const [language, translation] of Object.entries(catalogs)) {
  writeFileSync(
    `src/locales/messages/${language}.json`,
    JSON.stringify(translation, null, 2) + '\n',
  );
  writeFileSync(
    `src/locales/messages/${language}.mjs`,
    'export default ' + JSON.stringify(translation) + ';\n',
  );
}
writeFileSync(
  'src/locales/loaders.mjs',
  `// Generated by scripts/split-locales.mjs. Each catalog is loaded only when needed.\nexport default {\n${Object.keys(
    catalogs,
  )
    .filter((language) => language !== 'en')
    .map((language) => `${JSON.stringify(language)}:()=>import('./messages/${language}.mjs'),`)
    .join('\n')}\n};\n`,
);
console.log(`${Object.keys(catalogs).length} independently loadable locale catalogs.`);
